

CREATE TABLE IF NOT EXISTS ingested_file_log (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain VARCHAR(50) NOT NULL,
    file_path VARCHAR(1000) NOT NULL,
    last_modified_time TIMESTAMP NOT NULL,
    file_size BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    document_count INTEGER,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    last_ingested_at TIMESTAMP,
    last_error TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version		INTEGER NOT NULL DEFAULT 0,
    ingestion_request_id VARCHAR(150),

    CONSTRAINT uk_ingested_domain_file
        UNIQUE (domain, file_path),

    CONSTRAINT chk_ingested_file_status
        CHECK (status IN ('PROCESSING','COMPLETED','FAILED')),

    CONSTRAINT chk_ingested_file_size
        CHECK (file_size >= 0),

    CONSTRAINT chk_ingested_attempt_count
        CHECK (attempt_count >= 0),

    CONSTRAINT chk_ingested_document_count
        CHECK (document_count IS NULL OR document_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_ingested_file_status
    ON ingested_file_log (domain, status);

-- Safely updates the table if it already exists in PostgreSQL
ALTER TABLE ingested_file_log
    ADD COLUMN IF NOT EXISTS ingestion_request_id VARCHAR(255);